/**
 * Builds src/fonts.css: the self-hosted faces, Latin and Latin Extended
 * only, plus metric-matched fallback faces (EXPERIENCE-BUDGETS.md EB-8).
 *
 * Why only two subsets: bundlers that inline small assets (Bun does, with no
 * opt-out) embed every subset a stylesheet declares. Fontsource declares
 * seven per face; most documents use one. Other scripts fall back to the
 * system stack, which is the correct behavior for them anyway.
 *
 * Why fallbacks: with font-display: swap the page first paints in a system
 * font. Capsize sizes that system font to Literata's and Atkinson's metrics,
 * so the swap does not move the line being typed.
 */

import { createFontStack } from "@capsizecss/core";
import arial from "@capsizecss/metrics/arial";
import atkinsonHyperlegibleMono from "@capsizecss/metrics/atkinsonHyperlegibleMono";
import atkinsonHyperlegibleNext from "@capsizecss/metrics/atkinsonHyperlegibleNext";
import courierNew from "@capsizecss/metrics/courierNew";
import georgia from "@capsizecss/metrics/georgia";
import literata from "@capsizecss/metrics/literata";

export const SUBSETS = ["latin", "latin-ext"] as const;

const SOURCES = [
  { pkg: "@fontsource-variable/literata", files: ["opsz.css", "opsz-italic.css"] },
  { pkg: "@fontsource-variable/atkinson-hyperlegible-next", files: ["wght.css", "wght-italic.css"] },
  { pkg: "@fontsource-variable/atkinson-hyperlegible-mono", files: ["index.css"] },
];

/** Primary metrics paired with the local face that stands in for them. */
const FALLBACKS = [
  [literata, georgia],
  [atkinsonHyperlegibleNext, arial],
  [atkinsonHyperlegibleMono, courierNew],
] as const;

/** The name each fallback face gets: "Literata Fallback". Token font stacks list it right after the primary. */
export const FALLBACK_NAMES = FALLBACKS.map(([primary]) => `${primary.familyName} Fallback`);

function subsetOf(name: string): string | undefined {
  if (name.includes("-latin-ext-")) return "latin-ext";
  if (name.includes("-latin-")) return "latin";
  return undefined;
}

export async function buildFontsCss(): Promise<string> {
  const faces: string[] = [];
  for (const { pkg, files } of SOURCES) {
    for (const file of files) {
      const css = await Bun.file(Bun.resolveSync(`${pkg}/${file}`, import.meta.dir)).text();
      for (const match of css.matchAll(/\/\* ([\w-]+) \*\/\s*(@font-face\s*\{[^}]*\})/g)) {
        if (!subsetOf(match[1]!)) continue;
        faces.push(`/* ${match[1]} */\n${match[2]!.replace(/url\(\.\/files\/([^)]+)\)/g, `url("${pkg}/files/$1")`)}`);
      }
    }
  }
  const fallbacks = FALLBACKS.map((stack) => createFontStack([...stack], { fontFaceFormat: "styleString" }).fontFaces.trim());
  return [
    "/* Generated by scripts/build-fonts.ts from the fontsource packages and Capsize metrics. Do not edit. */",
    "/* Self-hosted faces (SIL OFL 1.1): Latin and Latin Extended only. Optional: hosts that bring their own fonts skip this file and override --nq-font-*. */",
    "",
    ...faces,
    "",
    "/* Metric-matched fallbacks (EB-8): the first paint uses these, so the swap to the real face does not reflow text. */",
    ...fallbacks,
    "",
  ].join("\n");
}
